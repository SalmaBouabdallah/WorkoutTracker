     private void calculateBMI() {
        try {
            double heightCm = Double.parseDouble(jTextFieldHeight.getText());
            double weightKg = Double.parseDouble(jTextFieldWeight.getText());
            
            double heightM = heightCm / 100;
            double bmi = weightKg / (heightM * heightM);
            bmi = Math.round(bmi * 10) / 10.0;
            
            jLabelBMI.setText(String.valueOf(bmi));
            
            String status;
            if (bmi < 18.5) {
                status = "Underweight";
                jLabelStatus.setForeground(new java.awt.Color(255, 165, 0));
            } else if (bmi < 25) {
                status = "Normal weight";
                jLabelStatus.setForeground(new java.awt.Color(0, 150, 0));
            } else if (bmi < 30) {
                status = "Overweight";
                jLabelStatus.setForeground(new java.awt.Color(255, 165, 0));
            } else {
                status = "Obese";
                jLabelStatus.setForeground(new java.awt.Color(200, 0, 0));
            }
            jLabelStatus.setText(status);
            
        } catch (NumberFormatException e) {
            jLabelBMI.setText("?");
            jLabelStatus.setText("Invalid numbers");
        }
    }

    
