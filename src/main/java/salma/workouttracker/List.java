        public void addWorkoutToTextArea(String date, String sport, String duration, String calories) {
        
        String workout = date + " | " + sport + " | " + duration + " min | " + calories + " kcal\n";
        jTextArea1.append(workout); 
         try(FileWriter f = new FileWriter("workouts.txt", true)) {
            f.write(workout);
        } catch(Exception e) {}
        
        }
        
         private void loadWorkouts() {
        try(BufferedReader r = new BufferedReader(new FileReader("workouts.txt"))) {
            String line;
            while((line = r.readLine()) != null) {
                jTextArea1.append(line + "\n");
            }
        } catch(Exception e) {}
    }
