private void showStats(){
    int total = 0;
    int totalMin = 0;
    int totalCal = 0;
    String bestExercise = "";
    int bestCal = 0;
    int squatCount = 0, deadliftCount = 0, chestCount = 0, pullCount = 0;
    
    try(BufferedReader r = new BufferedReader(new FileReader("workouts.txt"))){
        String line;
        while((line = r.readLine()) != null){
            
            String[] p;
            if (line.contains(" | ")) {
                p = line.split(" \\| ");
            } else if (line.contains("|")) {
                p = line.split("\\|");
            } else {
                continue; 
            }
            
            if (p.length < 4) continue;
            
            String ex = p[1].trim();
            
            
            String durationStr = p[2].trim().replaceAll("[^0-9]", "");
            
            String caloriesStr = p[3].trim().replaceAll("[^0-9]", "");
            
            if (durationStr.isEmpty() || caloriesStr.isEmpty()) continue;
            
            int min = Integer.parseInt(durationStr);
            int cal = Integer.parseInt(caloriesStr);
            
            total++;
            totalMin += min;
            totalCal += cal;
            
            if(cal > bestCal){
                bestCal = cal;
                bestExercise = ex;
            }
            
            if (ex.equalsIgnoreCase("Squats")) squatCount++;
            else if (ex.equalsIgnoreCase("Deadlifts")) deadliftCount++;
            else if (ex.equalsIgnoreCase("Chest Press")) chestCount++;
            else if (ex.equalsIgnoreCase("Pull Ups")) pullCount++;
        }
    } catch (Exception e){
        jLabelTotal.setText("Error: " + e.getMessage());
        return;
    }
    
    if (total == 0) {
        jLabelTotal.setText("No workouts");
        jLabelDuration.setText("0 min");
        jLabelCalories.setText("0");
        jLabelAvg.setText("0 min / 0 cal");
        jLabelBest.setText("None");
        jLabelFavorite.setText("None");
        return;
    }
    
    String fav = "Squats";
    int max = squatCount;
    if (deadliftCount > max){ max = deadliftCount; fav = "Deadlifts"; }
    if (chestCount > max){ max = chestCount; fav = "Chest Press"; }
    if (pullCount > max){ max = pullCount; fav = "Pull Ups"; }
    
    jLabelTotal.setText(String.valueOf(total));
    jLabelDuration.setText(totalMin + " min");
    jLabelCalories.setText(String.valueOf(totalCal));
    jLabelAvg.setText((totalMin/total) + " min / " + (totalCal/total) + " cal");
    jLabelBest.setText(bestExercise + " (" + bestCal + " cal)");
    jLabelFavorite.setText(fav + " (" + max + "x)");
}

