    private void jButton1MouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_jButton1MouseClicked
       String day= jDayComboBox.getSelectedItem().toString();
       String month= jMonthComboBox.getSelectedItem().toString();
       String year= jYearComboBox.getSelectedItem().toString();
       String sport= jSportComboBox.getSelectedItem().toString();
       String durationText=jDurationTextField.getText();
       
       
       if(day.equals("")|| month.equals("") || year.equals("") || sport.equals("") || durationText.equals("")){
           
           jLabel.setText("Fill in all the informations !");
       }
       else if (!durationText.matches("\\d+(\\.\\d+)?")){jLabel.setText("Duration must be a number !");}
       
       else{
            double duration = Double.parseDouble(durationText);
            
            double caloriesPerMinute = getCaloriesPerMinute(sport);
            double estimatedCalories = duration * caloriesPerMinute;
            
            int calories = (int) Math.round(estimatedCalories);
            String caloriesText = String.valueOf(calories);
            String date = day + " " + month + " " + year;
            String record = date + "|" + sport + "|" + durationText + "|" + caloriesText;
       
            List listInterface = new List();
            listInterface.addWorkoutToTextArea(date, sport, durationText, caloriesText);
            listInterface.setVisible(true);
        
        this.dispose();
           JOptionPane.showMessageDialog(this, "Workout Added to list !");
           
       }   
    }//GEN-LAST:event_jButton1MouseClicked
   private double getCaloriesPerMinute(String sport) {
    switch(sport) {
        
        case "Deadlifts":
            return 9.5;
        case "Squats":
            return 9.0;
        case "Pull Ups":
            return 8.5;
        case "Push Ups":
            return 8.0;
            
       
        case "Chest Press":
            return 7.5;
        case "Shoulder Press":
            return 7.5;
        case "Lat Pulldown":
            return 7.0;
        case "Leg Press":
            return 7.0;
            
       
        case "Bicep Curls":
            return 6.5;
        case "Tricep Extensions":
            return 6.5;
        case "Lunges":
            return 7.0;
            
       
        case "Plank":
            return 5.0;
            
       
        default:
            return 6.5;
    }
}
